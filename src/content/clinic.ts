/**
 * Single source of truth for clinic facts.
 *
 * Anything with `verified: false` is NEVER rendered on the site. When the clinic
 * confirms a detail, correct the value here and set `verified: true`; every page,
 * link, structured-data block and the appointment flow picks it up automatically.
 * See "Launch checklist" in README.md.
 */

export type PhoneNumber = {
  /** Digits with country code and a leading +, used in tel: links. */
  e164: string;
  display: string;
  verified: boolean;
};

export type ContactChannelConfig = {
  /** WhatsApp number as digits with country code and no +, e.g. 9779800000000. */
  whatsapp: { number: string; verified: boolean };
  email: { address: string; verified: boolean };
};

export type Clinician = {
  verified: boolean;
  name: string;
  title: string;
  qualifications: string[];
  registration: string;
  interests: string[];
  biography: string[];
  /** Key from src/content/images.ts; leave null to show a neutral monogram. */
  portrait: string | null;
};

export type Testimonial = {
  quote: string;
  author: string;
  source: string;
};

/**
 * A before and after result. Use only genuine photos of this clinic's own patients,
 * taken under comparable conditions. Nothing is published unless `consentOnFile`
 * is true, which means the patient gave documented permission for website use.
 */
export type BeforeAfterResult = {
  title: string;
  treatment: string;
  timeframe?: string;
  description: string;
  /** Paths such as /images/result-1-before.webp, generated by `npm run images`. */
  before: { src: string; alt: string };
  after: { src: string; alt: string };
  consentOnFile: boolean;
};

