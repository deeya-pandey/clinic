export const primaryPhone = () => {
  const { primary, secondary } = phoneNumbers;
  if (primary.verified) return primary;
  return secondary.verified ? secondary : null;
};

export const secondaryPhone = () => {
  const { primary, secondary } = phoneNumbers;
  return primary.verified && secondary.verified ? secondary : null;
};

export const verifiedWhatsapp = () =>
  contactChannels.whatsapp.verified && contactChannels.whatsapp.number
    ? contactChannels.whatsapp.number
    : null;

export const verifiedEmail = () =>
  contactChannels.email.verified && contactChannels.email.address
    ? contactChannels.email.address
    : null;

